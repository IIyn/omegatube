using System;
using System.Collections.Generic;
using OmegaTube.Config;
using OmegaTube.Data;
using OmegaTube.Ui;
using Tizen.NUI;

namespace OmegaTube
{
    public class App : NUIApplication
    {
        private readonly List<Screen> stack = new List<Screen>();
        private ConfirmDialog dialog;   // open modal question: gets every key
        private Splash splash;          // launch screen: keys wait until it is gone

        public AppConfig Config { get; private set; }
        public HomeScreen Home { get; private set; }
        // Latest GitHub release when newer than this build ({"version","url","notes"...}), else null.
        public object NewRelease { get; set; }
        public IntPtr EcoreWindow { get; private set; }

        protected override void OnCreate()
        {
            base.OnCreate();
            BugReport.Init(DirectoryInfo.Data);

            Window window = Window.Instance;
            // The video plane sits below the UI plane: screens paint their own opaque background,
            // the player screen leaves it transparent.
            window.SetTransparency(true);
            window.BackgroundColor = Color.Transparent;
            window.KeyEvent += OnKeyEvent;

            try
            {
                // Managed first: the UI language for the report screen if the core does not load.
                Config = AppConfig.Load(DirectoryInfo.Data);
                EnableDevLog();
                NativeCore.Init(DirectoryInfo.Data);
                BugReport.CoreLoaded = true;
                LocalStore.Init(DirectoryInfo.Data);
                NativeCore.SetLocale(Config.Language, Config.Region);
                EcoreWindow = GetEcoreWindow(window);
                Home = new HomeScreen(this);
                Push(Home);
            }
            catch (Exception e)
            {
                // Typically libomegacore.so failing to load on a TV we never tested: say so instead of
                // dropping back to the TV's menu.
                Tizen.Log.Error("OmegaTube", "startup: " + e);
                Push(new ReportScreen(this, BugReport.Describe(e), true));
                return;
            }

            string crash = BugReport.TakeCrash();
            splash = new Splash(() => Home.HasContent);
            splash.Closed += () =>
            {
                splash = null;
                if (crash != null)
                {
                    Push(new ReportScreen(this, crash, false));
                }
            };
            window.Add(splash);
            _ = RefreshRemote();
        }

        // Dev builds only: res/dev.json is generated by scripts/build-app.sh when OMEGA_DEV_LOG=host:port
        // is set, and mirrors the core log to that UDP listener (scripts/serve-test-media.sh).
        private void EnableDevLog()
        {
            try
            {
                string path = System.IO.Path.Combine(DirectoryInfo.Resource, "dev.json");
                if (!System.IO.File.Exists(path))
                {
                    return;
                }
                object dev = Util.Json.Parse(System.IO.File.ReadAllText(path));
                string host = Util.Json.Str(dev, "logHost");
                if (host.Length > 0)
                {
                    NativeCore.LogInitUdp(host, (int)Util.Json.Num(dev, "logPort", 5555));
                }
            }
            catch (Exception e)
            {
                Tizen.Log.Error("OmegaTube", "dev.json: " + e.Message);
            }
        }

        // Remote config (InnerTube clients...) then the GitHub release check, off the UI thread.
        private async System.Threading.Tasks.Task RefreshRemote()
        {
            await System.Threading.Tasks.Task.Run(() => YouTube.Call(NativeCore.ConfigRefresh()));
            if (!Config.CheckUpdates)
            {
                return;
            }
            object update = await System.Threading.Tasks.Task.Run(() => YouTube.Call(NativeCore.UpdateCheck()));
            if (Util.Json.Bool(update, "available"))
            {
                NewRelease = update;
                Home.ShowUpdate(Util.Json.Str(update, "version"), Util.Json.Str(update, "url"));
            }
        }

        public void Push(Screen screen)
        {
            if (stack.Count > 0)
            {
                Screen top = stack[stack.Count - 1];
                top.OnHide();
                top.Root.Hide();
            }
            stack.Add(screen);
            Window.Instance.Add(screen.Root);
            screen.OnShow();
        }

        public void Pop()
        {
            if (stack.Count <= 1)
            {
                Confirm(I18n.T("Do you want to quit OmegaTube?"), Exit);
                return;
            }
            Screen top = stack[stack.Count - 1];
            stack.RemoveAt(stack.Count - 1);
            top.OnHide();
            Window.Instance.Remove(top.Root);
            top.Root.Dispose();
            Screen below = stack[stack.Count - 1];
            below.Root.Show();
            below.OnShow();
        }

        // A screen rebuilding itself: on the stack (Replace) or hosted beside the home rail.
        public void ReplaceScreen(Screen old, Screen replacement)
        {
            if (stack.Count > 0 && stack[stack.Count - 1] == old)
            {
                Replace(replacement);
            }
            else
            {
                Home.ReplaceEmbedded(old, replacement);
            }
        }

        // Swaps the top screen (e.g. the player moving on to the next video).
        public void Replace(Screen screen)
        {
            if (stack.Count == 0)
            {
                Push(screen);
                return;
            }
            Screen top = stack[stack.Count - 1];
            stack.RemoveAt(stack.Count - 1);
            top.OnHide();
            Window.Instance.Remove(top.Root);
            top.Root.Dispose();
            stack.Add(screen);
            Window.Instance.Add(screen.Root);
            screen.OnShow();
        }

        // A playlist card opens the list to pick from; a mix (endless) plays right away.
        // Yes / No question over the current screen; onYes runs after it closes.
        public void Confirm(string question, Action onYes)
        {
            if (dialog != null)
            {
                return;
            }
            dialog = new ConfirmDialog(question, onYes);
            dialog.Closed += () => dialog = null;
            Window.Instance.Add(dialog);
        }

        public void Play(VideoItem item)
        {
            if (item.Kind == "playlist")
            {
                Push(new PlaylistScreen(this, item));
                return;
            }
            Push(new PlayerScreen(this, item));
        }

        private void OnKeyEvent(object sender, Window.KeyEventArgs e)
        {
            if (e.Key.State != Key.StateType.Down || stack.Count == 0 || splash != null)
            {
                return;
            }
            string key = e.Key.KeyPressedName;
            UiWork.KeyPressed();   // deferred card filling yields to navigation
            if (dialog != null)
            {
                dialog.OnKey(key);
                return;
            }
            if (!stack[stack.Count - 1].OnKey(key) && (key == "XF86Back" || key == "Escape"))
            {
                Pop();
            }
        }

        protected override void OnPause()
        {
            if (stack.Count > 0)
            {
                stack[stack.Count - 1].OnPause();
            }
            base.OnPause();
        }

        protected override void OnTerminate()
        {
            while (stack.Count > 1)
            {
                Pop();   // never reaches the quit question (the last screen stays)
            }
            base.OnTerminate();
        }

        // Ecore_Wl2_Window* of the NUI window. TizenFX 8 keeps the accessor internal, so go through reflection.
        private static IntPtr GetEcoreWindow(Window window)
        {
            var method = typeof(Window).GetMethod("GetNativeWindowHandler",
                System.Reflection.BindingFlags.Instance | System.Reflection.BindingFlags.Public | System.Reflection.BindingFlags.NonPublic);
            return method != null ? (IntPtr)method.Invoke(window, null) : IntPtr.Zero;
        }

        private static void Main(string[] args)
        {
            new App().Run(args);
        }
    }
}
